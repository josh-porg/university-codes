function [hair hO2 hN2] = enthalpycalculatorAir(Ti,T)

%Setting up enthalpy variables for O2 and N2
if T > 1000
   O2_Matrix = [0.03697578*10^2,0.06135197*10^-2,-0.1258842*10^-6,0.01775281*10^-9,-0.11364354*10^-14,-0.12339301*10^4];
    
   N2_Matrix = [0.0292664*10^2,0.14879768*10^-2,-0.0568476*10^-5,0.10097038*10^-9,-0.06753351*10^-13,-0.09227977*10^4];
    
elseif T <= 1000
    O2_Matrix = [0.03212936*10^2,0.11274864*10^-2,-0.0575615*10^-5,0.13138773*10^-8,-0.08768554*10^-11,-0.1005249*10^4];

    N2_Matrix = [0.03298677*10^2,0.14082404*10^-2,-0.03963222*10^-4,0.05641515*10^-7,-0.02444854*10^-10,-0.10208999*10^4];
    
end
    O2_Matrix_i = [0.03212936*10^2,0.11274864*10^-2,-0.0575615*10^-5,0.13138773*10^-8,-0.08768554*10^-11,-0.1005249*10^4];

    N2_Matrix_i = [0.03298677*10^2,0.14082404*10^-2,-0.03963222*10^-4,0.05641515*10^-7,-0.02444854*10^-10,-0.10208999*10^4];

Ti_Matrix = [Ti,(Ti^2)/2,(Ti^3)/3,(Ti^4)/4,(Ti^5)/5,1];
T_Matrix = [T,(T^2)/2,(T^3)/3,(T^4)/4,(T^5)/5,1];
hair = 8.314*(dot(Ti_Matrix,O2_Matrix_i)+3.76*dot(Ti_Matrix,N2_Matrix_i));
hO2 = 8.314*(dot(T_Matrix,O2_Matrix));
hN2 = 8.314*(dot(T_Matrix,N2_Matrix));
end