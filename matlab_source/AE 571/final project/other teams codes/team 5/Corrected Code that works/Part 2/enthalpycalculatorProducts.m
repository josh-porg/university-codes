function [h_CO2 h_H2O] = enthalpycalculatorProducts (T)

if T > 1000
    a1_CO2 = 0.04453623*10^2;
    a2_CO2 = 0.03140168*10^-1;
    a3_CO2 = -0.12784105*10^-5;
    a4_CO2 = 0.02393996*10^-8;
    a5_CO2 = -0.16690333*10^-13;
    a6_CO2 = -0.04896696*10^6;
    
    a1_H2O = 0.02672145*10^2;
    a2_H2O = 0.03056293*10^-1;
    a3_H2O = -0.08730260*10^-5;
    a4_H2O = 0.12009964*10^-9;
    a5_H2O = -0.06391618*10^-13;
    a6_H2O = -0.02989921*10^6;
elseif T <= 1000
    a1_CO2 = 0.02275724*10^2;
    a2_CO2 = 0.09922072*10^-1;
    a3_CO2 = -0.10409113*10^-4;
    a4_CO2 = 0.06866686*10^-7;
    a5_CO2 = -0.02117280*10^-10;
    a6_CO2 = -0.04837314*10^6;
    
    a1_H2O = 0.03386842*10^2;
    a2_H2O = 0.03474982*10^-1;
    a3_H2O = -0.06354696*10^-4;
    a4_H2O = 0.06968581*10^-7;
    a5_H2O = -0.02506588*10^-10;
    a6_H2O = -0.03020811*10^6;
end

h_CO2 = 8.314*(a6_CO2 + a1_CO2*T + a2_CO2/2*(T^2) + a3_CO2/3*(T^3) + a4_CO2/4*(T^4) + (a5_CO2/5)*(T^5));
h_H2O = 8.314*(a6_H2O + a1_H2O*T + a2_H2O/2*(T^2) + a3_H2O/3*(T^3) + a4_H2O/4*(T^4) + (a5_H2O/5)*(T^5));
end